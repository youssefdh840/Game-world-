// Helper to filter questions by Country Code
export function getQuestionsByCountry(countryCode: string): Question[] {
  const code = countryCode.toUpperCase();
  return QUESTIONS.filter((q) => q.countryCode.toUpperCase() === code);
}

// Backward-compatible category retrieval
export function getQuestionsByCategory(category: GameCategory, limit: number = 5): Question[] {
  const filtered = QUESTIONS.filter((q) => q.category === category);
  return shuffleArray(filtered).slice(0, limit);
}

// Backward-compatible random questions retrieval
export function getRandomQuestions(count: number = 5): Question[] {
  return shuffleArray([...QUESTIONS]).slice(0, count);
}

function shuffleArray<T>(arr: T[]): T[] {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}
